"""Generate 3D-only identities for sprites, Godot outposts and Android HUD.
No image rewriting or simulation changes. --check verifies generated files.
"""
from pathlib import Path
import argparse,json
ROOT=Path(__file__).resolve().parents[1]
SOURCE='art/source/palette-1.99/palette.json'

def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
    data=json.loads((ROOT/SOURCE).read_text('utf-8'))
    tiles=data['atlas_tile_by_seat'];gains=data['gain_by_seat'];rgb=data['atlas_rgb']
    assert sorted(tiles)==list(range(10)) and len(gains)==10 and len(rgb)==10
    assert all(len(row)==3 and all(0<v<=1 for v in row) for row in gains)
    colors=[''.join(f'{round(c*g):02x}' for c,g in zip(rgb[t],gains[i])) for i,t in enumerate(tiles)]
    heading='// Generated by tools/build_expedition_palette199.py; source '+SOURCE+'\n'
    glsl=heading+'vec4 expedition_palette(float seat) {\n'
    for i,(t,g) in enumerate(zip(tiles,gains)):
        glsl+=f'    if (seat < {i+.5:.1f}) return vec4({t:.1f},'+','.join(f'{v:.4f}' for v in g)+');\n'
    glsl+='    return vec4(1.0,.78,.90,.96);\n}\n'
    gd='# Generated by tools/build_expedition_palette199.py from '+SOURCE+'\nclass_name ExpeditionPalette extends RefCounted\nconst COLORS = ['+','.join(f'Color("{c}")' for c in colors)+']\n'
    java=heading+'package com.xenris.liquidwarsos;\nfinal class ExpeditionPalette {\n    private ExpeditionPalette() {}\n    private static final int[] COLORS={'+','.join('0xff'+c for c in colors)+'};\n    static int color(int team) { return COLORS[Math.max(0,Math.min(9,team))]; }\n}\n'
    outputs={'app/godot/expedition_palette.gdshaderinc':glsl,'app/godot/expedition_palette.gd':gd,'app/src/main/java/com/xenris/liquidwarsos/ExpeditionPalette.java':java}
    for name,text in outputs.items():
        file=ROOT/name
        if args.check:assert file.read_text('utf-8')==text,name
        else:file.write_text(text,'utf-8')
    print(('Verified' if args.check else 'Generated')+' 10 unique 3D seat identities; seat0 #'+colors[0])

if __name__=='__main__':main()
