"""Generate shared visual-only colour resources. GPL-3.0-or-later."""
from pathlib import Path
import json, re, argparse
ROOT=Path(__file__).resolve().parents[1]
def build(source='art/source/particles-1.63/palette.json'):
    p=json.loads((ROOT/source).read_text(encoding='utf8'))
    assert len(p['team_rgb'])==6
    for row in [*p['team_rgb'],p['game_background']]:assert len(row)==3 and all(0<=v<=255 for v in row)
    low,high=p['health_brightness'];assert 0<=low<=high<=1
    teams=',\n    '.join('{'+','.join(f'{v:.6f}f' for v in row)+'}' for row in p['team_rgb'])
    background=','.join(str(v) for v in p['game_background'])
    header=f'''// SPDX-License-Identifier: GPL-3.0-or-later
// Generated by tools/build_colour_palette.py from {source}.
#ifndef VISUAL_PALETTE_HPP
#define VISUAL_PALETTE_HPP
#include <algorithm>
namespace visual {{
static const unsigned char BACKGROUND[3] = {{{background}}};
static const float TEAM_RGB[6][3] = {{
    {teams}
}};
inline float healthLevel(float healthFraction) {{
    const float health=std::max(0.f,std::min(1.f,healthFraction));
    return {low:.6f}f+{high-low:.6f}f*health;
}}
inline void teamColour(int team,float healthFraction,float* output) {{
    if(team<0||team>=6)team=0;
    const float level=healthLevel(healthFraction);
    for(int c=0;c<3;c++)output[c]=TEAM_RGB[team][c]/255.f*level;
}}
}}
#endif
'''
    (ROOT/'app/src/main/cpp/application/visual_palette.hpp').write_text(header,encoding='utf8')
    color='#FF'+''.join(f'{v:02X}' for v in p['game_background'])
    (ROOT/'app/src/main/res/values/game_palette.xml').write_text(f'<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated from {source}. -->\n<resources><color name="game_background_soft">{color}</color></resources>\n',encoding='utf8')
    java_colors=','.join('0xff'+''.join(f'{v:02x}' for v in row) for row in p['team_rgb'])
    java=f'''// SPDX-License-Identifier: GPL-3.0-or-later
// Generated from {source}; same source as the native renderer.
package com.xenris.liquidwarsos;
public final class TeamPalette {{
    private TeamPalette() {{}}
    private static final int[] COLORS={{{java_colors}}};
    public static int color(int team) {{return COLORS[team>=0&&team<6?team:0];}}
}}
'''
    (ROOT/'app/src/main/java/com/xenris/liquidwarsos/TeamPalette.java').write_text(java,encoding='utf8')
    for locale,names in p.get('team_names',{}).items():
        assert len(names)==6
        path=ROOT/f'app/src/main/res/{locale}/strings.xml'
        text=path.read_text('utf8')
        array='<string-array name="teams_array">\n'+''.join(f'        <item>{name}</item>\n' for name in names)+'    </string-array>'
        text,count=re.subn(r'<string-array name="teams_array">.*?</string-array>',lambda _:array,text,flags=re.S)
        if not count:text=text.replace('</resources>',f'    {array}\n</resources>')
        assert count<=1
        path.write_text(text,encoding='utf8')
    print('Generated shared6-team palette and game background:',color)
if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--palette',default='art/source/particles-1.63/palette.json')
    build(parser.parse_args().palette)
