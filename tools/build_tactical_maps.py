"""Editable original asset exporter, not a game renderer. GPL-3.0-or-later."""
from pathlib import Path
import json, re, hashlib, copy, argparse
import numpy as np
from PIL import Image,ImageDraw,ImageFont
from scipy import ndimage as ndi
import build_fullscreen_maps as art
from tactical_map_designs import designs,convert
from fullscreen_map_designs import rect

ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'art/source/tactical-1.59'
OUT=ROOT/'docs/game/tactical-1.59'

def main():
    if "free_spawn.hpp" in (ROOT/"app/src/main/cpp/application/spawn.hpp").read_text("utf8"):
        raise RuntimeError("Historical1.59 exporter: use an isolated1.59 checkout; current1.60 assets are built by direct_free_maps.py")
    ap=argparse.ArgumentParser();ap.add_argument('--ids',nargs='*',type=int);args=ap.parse_args()
    plans=designs();art.SOURCE=SOURCE;art.load_palette(ROOT/'art/source/comfort-1.48/palette.json')
    art.PALETTES={k:(floor,tuple(round(c*.80) for c in base),rim) for k,(floor,base,rim) in art.PALETTES.items()}
    for p in [SOURCE/'svg',SOURCE/'geometry',OUT]:p.mkdir(parents=True,exist_ok=True)
    if args.ids is None:
        for path in (ROOT/'app/src/main/res').glob('values*/strings.xml'):
            text=path.read_text('utf8');zh=path.parent.name.startswith('values-zh')
            if 'name="maps_array"' not in text:continue  # Locale inherits base array.
            items=['随机地图' if zh else 'Random map']+[p['name_zh' if zh else 'name_en'] for p in plans]
            block='<string-array name="maps_array">\n'+''.join('        <item>'+s+'</item>\n' for s in items)+'    </string-array>'
            text,n=re.subn(r'<string-array name="maps_array">.*?</string-array>',lambda m:block,text,flags=re.S);assert n==1
            path.write_text(text,encoding='utf8')
    selected=[p for p in plans if args.ids is None or p['id'] in args.ids]
    inventory=[]
    for p in selected:
        wall=art.collision(p['ops']);labels,count=ndi.label(~wall)
        # Close sub-cell junction pinholes explicitly in editable geometry;
        # never carve a new shortcut through tactical boundaries.
        if count>1:
            sizes=np.bincount(labels.ravel());sizes[0]=0;main=int(sizes.argmax())
            for label in range(1,count+1):
                if label==main:continue
                assert sizes[label]<=4,(p['id'],'disconnected playable room')
                for y,x in zip(*np.where(labels==label)):
                    p['ops'].append(convert(rect(float(x),float(479-y),1,1)))
                p['connectivity_adjustments'].append(dict(kind='fill_junction_pinhole',cells=int(sizes[label])))
            wall=art.collision(p['ops'])
        assert ndi.label(~wall)[1]==1,(p['id'],'disconnected floor')
        art.save_svg(p)
        # Legacy id34 artwork has fixed team markers: suppress for every new map.
        visual=dict(p,id=-100);image,geometry=art.artwork(visual)
        image.save(art.RUNTIME/f'{p["id"]}-image.png',optimize=True)
        geometry.save(SOURCE/'geometry'/f'{p["id"]:02d}.png',optimize=True)
        mask=np.zeros((480,800,4),np.uint8);mask[wall]=255
        Image.fromarray(mask).save(art.RUNTIME/f'{p["id"]}-map.png',optimize=True)
        inventory.append(dict(id=p['id'],wall_fraction=float(wall.mean()),floor_components=1,
             image_sha256=hashlib.sha256((art.RUNTIME/f'{p["id"]}-image.png').read_bytes()).hexdigest(),
             mask_sha256=hashlib.sha256((art.RUNTIME/f'{p["id"]}-map.png').read_bytes()).hexdigest()))
        print(f'{p["id"]+1:02d} {p["name_en"]}: walls={wall.mean():.1%}',flush=True)
    if args.ids is not None:return
    (SOURCE/'maps.json').write_text(json.dumps(dict(license='GPL-3.0-or-later',canonical_size=[2200,1000],runtime_image_size=list(art.SIZE),rule_mask_size=[800,480],spawn_policy='Per-map deployment_centers; random safe coordinates and team assignment on each fresh match seed',maps=plans),ensure_ascii=False,indent=2),encoding='utf8')
    (OUT/'inventory.json').write_text(json.dumps(inventory,ensure_ascii=False,indent=2),encoding='utf8')
    header='// Generated by build_tactical_maps.py from editable maps.json. GPL-3.0-or-later\n#pragma once\nnamespace spawn { static constexpr short deployment[50][6][2]={\n'
    header+=''.join('{'+','.join('{'+str(x)+','+str(y)+'}' for x,y in p['deployment_centers'])+'},\n' for p in plans)
    (ROOT/'app/src/main/cpp/application/deployment.hpp').write_text(header+'};}\n',encoding='utf8')
    assert art.FONT.exists(),'Noto Sans SC OFL1.1 required'
    font=ImageFont.truetype(str(art.FONT),20)
    page=Image.new('RGB',(2200,10*235+52),(25,32,36));d=ImageDraw.Draw(page)
    d.text((18,12),'50 张迂回地图 · 素材总览，非游戏截图',font=font,fill=(190,206,207))
    for p in plans:
        i=p['id'];im=Image.open(art.RUNTIME/f'{i}-image.png');im.thumbnail((430,195));x=i%5*440+5;y=i//5*235+52;page.paste(im,(x,y));d.text((x+4,y+198),f'{i+1:02d} {p["name_zh"]}',font=font,fill=(180,198,199))
    page.save(OUT/'all-50-artwork.png');page.thumbnail((1536,1536));page.save(OUT/'all-50-artwork-preview.jpg',quality=85)
    (SOURCE/'README.md').write_text('# 50张迂回地图原件\n\nGPL-3.0-or-later，本项目原创参数化几何。maps.json和svg为编辑原件，geometry为高分辨率轮廓，导出器tools/build_tactical_maps.py与tactical_map_designs.py随源码交付。复用柔和暮色色板，未使用外部付费素材。总览字体Noto Sans SC，SIL OFL1.1，商业使用允许（许可见art/source/ui-1.52/NotoSansSC-OFL.txt）。\n',encoding='utf8')

if __name__=='__main__':main()
